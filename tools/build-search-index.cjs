// Builds assets/search-index.js from the site's own HTML, so search always
// covers exactly what the pages say. No dependencies.
// Run after changing page content:  node tools/build-search-index.cjs
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const PAGES = [
  ['index.html', '/', 'Home'],
  ['for/game-studios.html', '/for/game-studios', 'For game studios'],
  ['for/kickstarter.html', '/for/kickstarter', 'For Kickstarter creators'],
  ['for/agencies.html', '/for/agencies', 'For agencies'],
  ['gta6.html', '/gta6', 'GTA VI creators'],
  ['guildstew.html', '/guildstew', 'Case D · Guildstew'],
  ['aurora.html', '/aurora', 'Case A · Aurora'],
  ['crimson.html', '/crimson', 'Case B · Crimson'],
  ['site202.html', '/site202', 'Case C · Site-202'],
  ['archive.html', '/archive', 'Archive'],
  ['imprint.html', '/imprint', 'Imprint'],
  ['privacy.html', '/privacy', 'Privacy'],
];

const ENT = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', ldquo: '“', rdquo: '”', lsquo: '‘', rsquo: '’',
  mdash: '—', ndash: '–', hellip: '…', middot: '·', rarr: '→', larr: '←', times: '×', asymp: '≈' };
function decode(s) {
  return s.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (m, e) => {
    if (e[0] === '#') return String.fromCodePoint(e[1] === 'x' || e[1] === 'X' ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10));
    return ENT[e.toLowerCase()] ?? m;
  });
}
function text(html) {
  return decode(html
    .replace(/<(script|style|svg|canvas|noscript)\b[^>]*>[\s\S]*?<\/\1>/gi, ' ')
    .replace(/<br\s*\/?>/gi, ' ')
    .replace(/<\/(p|div|li|h\d|figcaption|summary|blockquote|span)>/gi, ' ')
    .replace(/<[^>]+>/g, ''))
    .replace(/\s+/g, ' ').trim();
}
function first(re, html) { const m = html.match(re); return m ? text(m[1]) : ''; }
function attr(tag, name) { const m = tag.match(new RegExp('\\s' + name + '="([^"]*)"')); return m ? m[1] : ''; }

const out = [];
const seen = new Set();
function push(e) {
  if (!e.t || !e.x) return;
  const key = e.u + '|' + e.t;
  if (seen.has(key)) return;
  seen.add(key);
  e.x = e.x.length > 1400 ? e.x.slice(0, 1400) + '…' : e.x;
  out.push(e);
}

for (const [file, url, label] of PAGES) {
  let html = fs.readFileSync(path.join(root, file), 'utf8');
  const title = decode((html.match(/<title>([\s\S]*?)<\/title>/i) || [, label])[1]).trim();
  const desc = decode((html.match(/<meta name="description" content="([^"]*)"/i) || [, ''])[1]);
  // chrome is the same on every page; only the page body is indexed
  const body = (html.match(/<main\b[^>]*>([\s\S]*?)<\/main>/i) || [, html])[1];

  push({ t: title.replace(/\s+—\s+Joey.*$/, '').replace(/^Joey in Sync — /, ''), p: label, u: url, x: desc || text(body).slice(0, 300) });

  // sections, in document order, with the id that anchors them
  const secRe = /<(section|header)\b([^>]*)>([\s\S]*?)<\/\1>/gi;
  const sections = [];
  let m;
  while ((m = secRe.exec(body))) sections.push({ at: m.index, end: secRe.lastIndex, tag: m[2], html: m[3] });

  for (const s of sections) {
    const id = attr(s.tag, 'id');
    const heading = first(/<h[12]\b[^>]*>([\s\S]*?)<\/h[12]>/i, s.html)
      || first(/<span class="t">([\s\S]*?)<\/span>/i, s.html)
      || attr(s.tag, 'aria-label') || attr(s.tag, 'data-chapter-name');
    const u = id ? url + '#' + id : url;
    push({ t: heading, p: label, u, x: text(s.html) });

    // cards, records, answers and references inside the section get their own entries
    const itemRe = /<(article|details|figure)\b([^>]*)>([\s\S]*?)<\/\1>/gi;
    let it;
    while ((it = itemRe.exec(s.html))) {
      const cls = attr(it[2], 'class');
      if (it[1] === 'figure' && !/\b(lref|ref|proof-q|hero-proof)\b/.test(cls)) continue;
      const t = first(/<(?:h3|h2|summary)\b[^>]*>([\s\S]*?)<\/(?:h3|h2|summary)>/i, it[3])
        || first(/<b\b[^>]*>([\s\S]*?)<\/b>/i, it[3]) || heading;
      const x = text(it[3]);
      const tt = it[1] === 'figure' ? 'Reference — ' + (first(/<b\b[^>]*>([\s\S]*?)<\/b>/i, it[3]) || heading) : t;
      push({ t: tt, p: label, u, x });
    }
  }
}

const js = '/* generated by tools/build-search-index.cjs — do not edit by hand */\n' +
  'window.SEARCH_INDEX=' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(root, 'assets/search-index.js'), js);
console.log(out.length + ' entries, ' + Math.round(js.length / 1024) + ' KB');
